create table servico (
    id              bigint generated by default as identity primary key,
    nome            varchar(100)  not null,
    descricao       varchar(255),
    preco           numeric(10,2) not null,
    duracao_minutos integer       not null,
    ativo           boolean       not null default true
);

create table barbeiro (
    id    bigint generated by default as identity primary key,
    nome  varchar(100) not null,
    ativo boolean      not null default true
);

create table agendamento (
    id                  uuid primary key,
    servico_id          bigint        not null references servico(id),
    barbeiro_id         bigint        not null references barbeiro(id),
    cliente_nome        varchar(100)  not null,
    cliente_telefone    varchar(20)   not null,
    cliente_email       varchar(150)  not null,
    inicio              timestamp     not null,
    fim                 timestamp     not null,
    valor_total         numeric(10,2) not null,
    valor_sinal         numeric(10,2) not null,
    status              varchar(30)   not null,
    expira_em           timestamp     not null,
    pagamento_id        varchar(100),
    pix_copia_e_cola    varchar(2000),
    pix_qr_code_base64  text,
    pix_url             varchar(1000),
    criado_em           timestamp     not null,
    pago_em             timestamp,
    versao              bigint        not null default 0
);

create index idx_agendamento_barbeiro_inicio on agendamento (barbeiro_id, inicio);
create index idx_agendamento_status on agendamento (status);
create unique index uk_agendamento_pagamento on agendamento (pagamento_id);

